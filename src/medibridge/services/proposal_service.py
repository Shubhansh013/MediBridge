"""Stock-proposal orchestration service for MediBridge.

Coordinates chemist authorization, natural-language parsing, catalogue
resolution, proposal adaptation, and pending proposal creation without
modifying inventory.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
import inspect
from typing import Any, Optional, Protocol, Sequence
from pydantic import BaseModel, ConfigDict, Field

from medibridge.schemas.stock import (
    ParsedMedicineStockItem,
    StockActionEnum,
    StockUpdateProposal,
)
from medibridge.services.ai_parser import parse_stock_message
from medibridge.services.proposal_adapter import (
    AdaptedProposalResult,
    ParsedProposalInput,
    UnresolvedProposalItem,
    adapt_parsed_item,
    adapt_stock_proposal,
    compute_review_flag,
)


class CatalogueMedicine(BaseModel):
    """Represents a medicine catalogue entry as defined in docs/CONTRACT.md.

    Used by the service layer to resolve generic salts, standard strengths,
    and Schedule H classification from chemist brand mentions.
    """

    model_config = ConfigDict(extra="forbid")

    id: int = Field(..., description="Primary key in medicine catalogue.")
    brand_name: str = Field(..., description="Brand name of the medicine (e.g. 'Dolo 650').")
    generic_name: str = Field(..., description="Active chemical salt (e.g. 'paracetamol').")
    strength: Optional[str] = Field(default=None, description="Standard strength (e.g. '650mg').")
    form: Optional[str] = Field(default=None, description="Standard dosage form (e.g. 'tablet', 'strip').")
    is_schedule_h: bool = Field(default=False, description="Whether restricted under Schedule H.")
    aliases: list[str] = Field(default_factory=list, description="Common aliases, misspellings, or Hinglish terms.")


class StoredProposalRecord(BaseModel):
    """Represents an unconfirmed proposal stored in the database.

    Matches the fields of the stock_proposals table defined in docs/CONTRACT.md.
    Crucially, status is always 'PENDING' upon creation.
    """

    model_config = ConfigDict(extra="forbid")

    id: int = Field(..., description="Proposal ID generated by the database.")
    pharmacy_id: int = Field(..., description="Target pharmacy ID.")
    chemist_user_id: int = Field(..., description="Chemist user ID who sent the update.")
    raw_message: str = Field(..., description="Original raw message for traceability.")
    brand_name: Optional[str] = Field(default=None, description="Identified brand name.")
    parsed_salt: str = Field(..., description="Generic active salt.")
    parsed_strength: str = Field(..., description="Potency/strength.")
    parsed_form: Optional[str] = Field(default=None, description="Dosage form.")
    parsed_quantity: Optional[int] = Field(default=None, ge=0, description="Parsed quantity.")
    parsed_intent: StockActionEnum = Field(..., description="Stock status intent.")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Match/parse confidence.")
    status: str = Field(default="PENDING", description="Proposal state; always PENDING at creation.")
    flagged_for_review: bool = Field(..., description="True if review is mandatory.")
    expires_at: datetime = Field(..., description="Proposal expiry timestamp (typically created_at + 24h).")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    confirmed_by: Optional[int] = Field(default=None, description="Chemist/pharmacist user ID who confirmed this proposal.")
    confirmed_at: Optional[datetime] = Field(default=None, description="Timestamp when confirmed.")
    review_note: Optional[str] = Field(default=None, description="Pharmacist/chemist review or rejection note.")
    renewed_from_id: Optional[int] = Field(default=None, description="Source proposal ID if this proposal renewed an expired one.")


class StockProposalRepositoryProtocol(Protocol):
    """Minimal repository protocol required for stock proposal processing.

    Contains only the data access methods necessary for proposal creation
    and authorization checks, without inventory mutation.
    """

    def is_user_linked_to_pharmacy(self, user_id: int, pharmacy_id: int) -> bool:
        """Check if user has an active membership at the specified pharmacy."""
        ...

    def find_medicine_by_alias(self, alias: str) -> Optional[CatalogueMedicine]:
        """Find a single medicine by exact alias match."""
        ...

    def search_medicines(self, query: str, limit: int = 5) -> list[CatalogueMedicine]:
        """Search catalogue medicines by query across brand, generic, and aliases."""
        ...

    def create_stock_proposal(
        self,
        pharmacy_id: int,
        chemist_user_id: int,
        raw_message: str,
        parsed: ParsedProposalInput,
    ) -> StoredProposalRecord:
        """Create and persist a PENDING stock proposal row."""
        ...


class ProposalServiceStatus(str, Enum):
    """Status enum for proposal service processing outcome."""

    SUCCESS = "SUCCESS"
    PARTIAL_SUCCESS = "PARTIAL_SUCCESS"
    UNRESOLVED = "UNRESOLVED"
    UNPARSEABLE = "UNPARSEABLE"
    UNAUTHORIZED = "UNAUTHORIZED"


class ProposalServiceResult(BaseModel):
    """Structured result returned by the proposal orchestration service."""

    model_config = ConfigDict(extra="forbid")

    status: ProposalServiceStatus = Field(..., description="Overall processing outcome.")
    raw_message: str = Field(..., description="Chemist's input message.")
    pharmacy_id: int = Field(..., description="Target pharmacy ID.")
    chemist_user_id: int = Field(..., description="Chemist user ID.")
    created_proposals: list[StoredProposalRecord] = Field(
        default_factory=list,
        description="List of persisted PENDING proposals.",
    )
    unresolved_items: list[UnresolvedProposalItem] = Field(
        default_factory=list,
        description="List of parsed items that require catalogue clarification.",
    )
    reason: Optional[str] = Field(
        default=None,
        description="Reason or explanatory notes (e.g., authorization error or parse notes).",
    )
    source_message_ref: Optional[str] = Field(
        default=None,
        description="Optional unique reference for grouping multi-medicine updates.",
    )


def process_stock_message(
    raw_message: str,
    pharmacy_id: int,
    chemist_user_id: int,
    repository: StockProposalRepositoryProtocol,
    *,
    source_message_ref: Optional[str] = None,
) -> ProposalServiceResult:
    """Orchestrates authorization, message parsing, catalogue lookup, and proposal creation.

    Steps:
    1. Verifies that the acting chemist is actively linked to the target pharmacy.
    2. Parses the raw message into structured medicine items (offline, deterministic).
    3. Queries the catalogue to resolve active chemical salts, standard strengths, and
       Schedule H classification without inventing metadata or guessing ambiguous matches.
    4. Adapts items into validated database payloads.
    5. Persists resolved items as PENDING proposals via repository.create_stock_proposal.
    6. Returns a structured result categorizing the outcome.

    Args:
        raw_message: The chemist's chat message text.
        pharmacy_id: Target pharmacy identifier.
        chemist_user_id: Telegram / system user ID of the chemist.
        repository: Data access provider implementing StockProposalRepositoryProtocol.
        source_message_ref: Optional external reference (e.g. Telegram message ID) for grouping.

    Returns:
        ProposalServiceResult containing status, created proposals, and unresolved items.
    """
    # 1. Authorization check
    if not repository.is_user_linked_to_pharmacy(chemist_user_id, pharmacy_id):
        return ProposalServiceResult(
            status=ProposalServiceStatus.UNAUTHORIZED,
            raw_message=raw_message if isinstance(raw_message, str) else "",
            pharmacy_id=pharmacy_id,
            chemist_user_id=chemist_user_id,
            reason=f"User {chemist_user_id} is not linked to pharmacy {pharmacy_id}.",
            source_message_ref=source_message_ref,
        )

    # 2. Input validation
    if not isinstance(raw_message, str) or not raw_message.strip():
        return ProposalServiceResult(
            status=ProposalServiceStatus.UNPARSEABLE,
            raw_message=raw_message if isinstance(raw_message, str) else "",
            pharmacy_id=pharmacy_id,
            chemist_user_id=chemist_user_id,
            reason="Empty or non-string message provided.",
            source_message_ref=source_message_ref,
        )

    # 3. Parsing message
    parsed_proposal: Optional[StockUpdateProposal] = parse_stock_message(raw_message)
    if parsed_proposal is None:
        return ProposalServiceResult(
            status=ProposalServiceStatus.UNPARSEABLE,
            raw_message=raw_message,
            pharmacy_id=pharmacy_id,
            chemist_user_id=chemist_user_id,
            reason="Message could not be parsed as a current stock update (conversational, uncertain, or future-oriented).",
            source_message_ref=source_message_ref,
        )

    # 4. Catalogue Matching for each parsed item
    catalogue_matches: dict[str, dict[str, Any]] = {}
    custom_unresolved: list[UnresolvedProposalItem] = []

    for item in parsed_proposal.items:
        med_name = item.medicine_name.strip()

        # Step 3A: Direct alias match
        matched_med = repository.find_medicine_by_alias(med_name)
        confidence: Optional[float] = None

        if matched_med is not None:
            confidence = 1.0
        else:
            # Step 3B: Catalogue search
            candidates = repository.search_medicines(med_name, limit=5)
            if len(candidates) == 1:
                matched_med = candidates[0]
                # High confidence if exact brand match (case-insensitive)
                if matched_med.brand_name.strip().lower() == med_name.lower():
                    confidence = 1.0
                else:
                    # Partial / fuzzy match receives lower confidence, triggering pharmacist review
                    confidence = 0.75
            elif len(candidates) > 1:
                # Ambiguous matches: do NOT guess
                custom_unresolved.append(
                    UnresolvedProposalItem(
                        item=item,
                        raw_message=raw_message,
                        missing_fields=["parsed_salt", "confidence", "is_schedule_h"],
                        reason=(
                            f"Multiple catalogue matches found for '{med_name}': "
                            f"{[c.brand_name for c in candidates]}. Specific clarification required."
                        ),
                    )
                )
                continue
            else:
                # Unknown medicine (0 candidates): do NOT invent salt
                custom_unresolved.append(
                    UnresolvedProposalItem(
                        item=item,
                        raw_message=raw_message,
                        missing_fields=["parsed_salt", "confidence", "is_schedule_h"],
                        reason=f"Medicine '{med_name}' not found in catalogue. Generic salt unknown.",
                    )
                )
                continue

        # Check strength: must come from message or catalogue
        resolved_strength = item.strength or (matched_med.strength if matched_med else None)
        resolved_form = (matched_med.form if matched_med and matched_med.form else item.dosage_form)

        if not resolved_strength:
            # Strength missing in both message and catalogue: do NOT fabricate
            custom_unresolved.append(
                UnresolvedProposalItem(
                    item=item,
                    raw_message=raw_message,
                    missing_fields=["parsed_strength"],
                    reason=f"Strength not specified in message and not defined in catalogue for '{med_name}'.",
                )
            )
            continue

        assert matched_med is not None
        assert confidence is not None
        catalogue_matches[item.medicine_name] = {
            "brand_name": matched_med.brand_name,
            "salt": matched_med.generic_name,
            "strength": resolved_strength,
            "form": resolved_form,
            "confidence": confidence,
            "is_schedule_h": matched_med.is_schedule_h,
        }

    # 4. Adaptation
    adapted_result: AdaptedProposalResult = adapt_stock_proposal(
        parsed_proposal,
        catalogue_matches=catalogue_matches,
    )

    # Combine adapted unresolved items with our custom detailed unresolved items
    all_unresolved: list[UnresolvedProposalItem] = list(custom_unresolved)
    # Add any unresolved items from adapter that weren't already captured in custom_unresolved
    custom_item_names = {u.item.medicine_name for u in custom_unresolved}
    for unresolved_item in adapted_result.unresolved:
        if unresolved_item.item.medicine_name not in custom_item_names:
            all_unresolved.append(unresolved_item)

    # 5. Create PENDING proposals for resolved items
    created_proposals: list[StoredProposalRecord] = []
    for resolved_input in adapted_result.resolved:
        try:
            sig = inspect.signature(repository.create_stock_proposal)
            has_ref = "source_message_ref" in sig.parameters
        except (ValueError, TypeError):
            has_ref = False

        if has_ref and source_message_ref is not None:
            proposal_record = repository.create_stock_proposal(
                pharmacy_id=pharmacy_id,
                chemist_user_id=chemist_user_id,
                raw_message=raw_message,
                parsed=resolved_input,
                source_message_ref=source_message_ref,
            )
        else:
            proposal_record = repository.create_stock_proposal(
                pharmacy_id=pharmacy_id,
                chemist_user_id=chemist_user_id,
                raw_message=raw_message,
                parsed=resolved_input,
            )
        created_proposals.append(proposal_record)

    # 6. Determine service outcome status
    if created_proposals and not all_unresolved:
        service_status = ProposalServiceStatus.SUCCESS
        reason = f"Successfully created {len(created_proposals)} pending proposal(s)."
    elif created_proposals and all_unresolved:
        service_status = ProposalServiceStatus.PARTIAL_SUCCESS
        reason = (
            f"Created {len(created_proposals)} pending proposal(s), "
            f"but {len(all_unresolved)} item(s) require clarification."
        )
    else:
        service_status = ProposalServiceStatus.UNRESOLVED
        reason = f"All {len(all_unresolved)} medicine item(s) could not be resolved against the catalogue."

    return ProposalServiceResult(
        status=service_status,
        raw_message=raw_message,
        pharmacy_id=pharmacy_id,
        chemist_user_id=chemist_user_id,
        created_proposals=created_proposals,
        unresolved_items=all_unresolved,
        reason=reason,
        source_message_ref=source_message_ref,
    )
